"""The FRC RAG stack: content bucket, Bedrock Knowledge Base on S3 Vectors, chat Lambda, audit
table, and budget guardrails. See docs/discovery.md for why each piece is shaped this way."""

from pathlib import Path

from aws_cdk import CfnOutput, Duration, RemovalPolicy, Stack
from aws_cdk import aws_bedrock as bedrock
from aws_cdk import aws_budgets as budgets
from aws_cdk import aws_dynamodb as dynamodb
from aws_cdk import aws_iam as iam
from aws_cdk import aws_lambda as lambda_
from aws_cdk import aws_logs as logs
from aws_cdk import aws_s3 as s3
from aws_cdk import aws_s3vectors as s3vectors
from constructs import Construct

from .config import DeployConfig
from .github_access import GitHubAccess
from .student_access import StudentAccess

EMBEDDING_MODEL = "amazon.titan-embed-text-v2:0"
EMBEDDING_DIMENSIONS = 1024
CHUNKS_PREFIX = "kb/"  # chunk files; manifests live under manifests/ and are not indexed


class FrcRagStack(Stack):
    def __init__(
        self,
        scope: Construct,
        construct_id: str,
        *,
        config: DeployConfig,
        chat_code: Path,
        backend_dir: Path,
        web_dir: Path,
        stream_code: Path | None = None,
        **kwargs,
    ):
        super().__init__(scope, construct_id, **kwargs)

        content = s3.Bucket(
            self,
            "Content",
            block_public_access=s3.BlockPublicAccess.BLOCK_ALL,
            encryption=s3.BucketEncryption.S3_MANAGED,
            enforce_ssl=True,
            # Everything in here is regenerated by `kb ingest` + `kb sync`.
            removal_policy=RemovalPolicy.DESTROY,
            auto_delete_objects=True,
        )

        vector_bucket = s3vectors.CfnVectorBucket(self, "Vectors")
        vector_bucket.apply_removal_policy(RemovalPolicy.DESTROY)
        index = s3vectors.CfnIndex(
            self,
            "VectorIndex",
            vector_bucket_arn=vector_bucket.attr_vector_bucket_arn,
            index_name="frc-kb",
            data_type="float32",
            dimension=EMBEDDING_DIMENSIONS,
            distance_metric="cosine",
            # Bedrock stores chunk text in vector metadata; it must not count toward the
            # 2 KB filterable-metadata limit.
            metadata_configuration=s3vectors.CfnIndex.MetadataConfigurationProperty(
                non_filterable_metadata_keys=["AMAZON_BEDROCK_TEXT", "AMAZON_BEDROCK_METADATA"]
            ),
        )
        index.apply_removal_policy(RemovalPolicy.DESTROY)

        embedding_model_arn = f"arn:aws:bedrock:{self.region}::foundation-model/{EMBEDDING_MODEL}"
        kb_role = iam.Role(
            self,
            "KnowledgeBaseRole",
            assumed_by=iam.ServicePrincipal(
                "bedrock.amazonaws.com", conditions={"StringEquals": {"aws:SourceAccount": self.account}}
            ),
        )
        kb_policy = iam.Policy(
            self,
            "KnowledgeBasePolicy",
            roles=[kb_role],
            statements=[
                iam.PolicyStatement(actions=["bedrock:InvokeModel"], resources=[embedding_model_arn]),
                iam.PolicyStatement(actions=["s3:ListBucket"], resources=[content.bucket_arn]),
                iam.PolicyStatement(actions=["s3:GetObject"], resources=[content.arn_for_objects(f"{CHUNKS_PREFIX}*")]),
                iam.PolicyStatement(
                    actions=[
                        "s3vectors:GetIndex",
                        "s3vectors:PutVectors",
                        "s3vectors:GetVectors",
                        "s3vectors:DeleteVectors",
                        "s3vectors:ListVectors",
                        "s3vectors:QueryVectors",
                    ],
                    resources=[index.attr_index_arn],
                ),
            ],
        )

        knowledge_base = bedrock.CfnKnowledgeBase(
            self,
            "KnowledgeBase",
            name=f"{construct_id}-kb",
            description="FRC design, CAD and fabrication references",
            role_arn=kb_role.role_arn,
            knowledge_base_configuration=bedrock.CfnKnowledgeBase.KnowledgeBaseConfigurationProperty(
                type="VECTOR",
                vector_knowledge_base_configuration=bedrock.CfnKnowledgeBase.VectorKnowledgeBaseConfigurationProperty(
                    embedding_model_arn=embedding_model_arn,
                    embedding_model_configuration=bedrock.CfnKnowledgeBase.EmbeddingModelConfigurationProperty(
                        bedrock_embedding_model_configuration=bedrock.CfnKnowledgeBase.BedrockEmbeddingModelConfigurationProperty(
                            dimensions=EMBEDDING_DIMENSIONS, embedding_data_type="FLOAT32"
                        )
                    ),
                ),
            ),
            storage_configuration=bedrock.CfnKnowledgeBase.StorageConfigurationProperty(
                type="S3_VECTORS",
                s3_vectors_configuration=bedrock.CfnKnowledgeBase.S3VectorsConfigurationProperty(
                    index_arn=index.attr_index_arn, vector_bucket_arn=vector_bucket.attr_vector_bucket_arn
                ),
            ),
        )
        # Bedrock checks the role's access when the KB is created.
        knowledge_base.node.add_dependency(kb_policy)

        data_source = bedrock.CfnDataSource(
            self,
            "ContentSource",
            name="content",
            knowledge_base_id=knowledge_base.attr_knowledge_base_id,
            data_deletion_policy="DELETE",
            data_source_configuration=bedrock.CfnDataSource.DataSourceConfigurationProperty(
                type="S3",
                s3_configuration=bedrock.CfnDataSource.S3DataSourceConfigurationProperty(
                    bucket_arn=content.bucket_arn, inclusion_prefixes=[CHUNKS_PREFIX]
                ),
            ),
            # Files are pre-chunked by `kb ingest`; one file is one chunk.
            vector_ingestion_configuration=bedrock.CfnDataSource.VectorIngestionConfigurationProperty(
                chunking_configuration=bedrock.CfnDataSource.ChunkingConfigurationProperty(chunking_strategy="NONE")
            ),
        )

        table = dynamodb.TableV2(
            self,
            "AppTable",
            partition_key=dynamodb.Attribute(name="pk", type=dynamodb.AttributeType.STRING),
            sort_key=dynamodb.Attribute(name="sk", type=dynamodb.AttributeType.STRING),
            billing=dynamodb.Billing.on_demand(),
            time_to_live_attribute="expires_at",
            point_in_time_recovery_specification=dynamodb.PointInTimeRecoverySpecification(
                point_in_time_recovery_enabled=True
            ),
            removal_policy=RemovalPolicy.RETAIN,  # audit log
        )

        chat_environment = {
            "KNOWLEDGE_BASE_ID": knowledge_base.attr_knowledge_base_id,
            "TABLE_NAME": table.table_name,
            "MODEL_ID": config.model_id,
            "CLAUDE_ENDPOINT": config.model_endpoint,
            "MAX_TOKENS": str(config.max_tokens),
            "EFFORT": config.effort,
            "TOP_K": str(config.top_k),
            "USER_DAILY_LIMIT_USD": str(config.user_daily_usd),
            "MONTHLY_LIMIT_USD": str(config.monthly_usd),
            "PRICE_INPUT_PER_MTOK": str(config.price_input_per_mtok),
            "PRICE_OUTPUT_PER_MTOK": str(config.price_output_per_mtok),
            "AUDIT_RETENTION_DAYS": str(config.audit_retention_days),
            "CHAT_RETENTION_DAYS": str(config.chat_retention_days),
        }
        chat = lambda_.Function(
            self,
            "ChatFunction",
            runtime=lambda_.Runtime.PYTHON_3_13,
            architecture=lambda_.Architecture.ARM_64,
            handler="chat_api.handler.lambda_handler",
            code=lambda_.Code.from_asset(str(chat_code)),
            memory_size=512,
            timeout=Duration.seconds(60),
            reserved_concurrent_executions=config.lambda_reserved_concurrency or None,
            log_group=logs.LogGroup(
                self, "ChatLogs", retention=logs.RetentionDays.THREE_MONTHS, removal_policy=RemovalPolicy.DESTROY
            ),
            environment=chat_environment,
        )
        chat.add_to_role_policy(iam.PolicyStatement(actions=["bedrock:Retrieve"], resources=[knowledge_base.attr_knowledge_base_arn]))
        if config.model_endpoint == "mantle":
            # Claude in Amazon Bedrock (bedrock-mantle endpoint). Model ARNs for this action aren't
            # documented yet; the app-level caps and the Budgets deny below bound spend regardless.
            chat.add_to_role_policy(iam.PolicyStatement(actions=["bedrock-mantle:CreateInference"], resources=["*"]))
        else:
            # InvokeModel through a cross-region inference profile (e.g. us.anthropic...): the
            # profile in this region, plus the model in whichever region the profile routes to.
            model = config.model_id.split(".", 1)[1] if config.model_id.startswith(("us.", "global.")) else config.model_id
            chat.add_to_role_policy(
                iam.PolicyStatement(
                    actions=["bedrock:InvokeModel"],
                    resources=[
                        f"arn:aws:bedrock:{self.region}:{self.account}:inference-profile/{config.model_id}",
                        f"arn:aws:bedrock:*::foundation-model/{model}",
                    ],
                )
            )
        chat.add_to_role_policy(
            iam.PolicyStatement(
                actions=["dynamodb:GetItem", "dynamodb:PutItem", "dynamodb:UpdateItem", "dynamodb:Query", "dynamodb:DeleteItem"],
                resources=[table.table_arn],
            )
        )

        self._budget_guardrails(config, roles=[chat.role, kb_role])
        StudentAccess(
            self,
            "StudentAccess",
            config=config,
            backend_dir=backend_dir,
            web_dir=web_dir,
            table=table,
            chat=chat,
            # The streaming function shares the chat role, so it has the same rights and the same
            # Budgets kill switch.
            stream_code=stream_code or chat_code,
            chat_role=chat.role,
            chat_environment=chat_environment,
        )
        if config.github_repo:
            GitHubAccess(
                self, "GitHubAccess", repo=config.github_repo, content=content, knowledge_base_arn=knowledge_base.attr_knowledge_base_arn
            )

        CfnOutput(self, "ContentBucketName", value=content.bucket_name)
        CfnOutput(self, "KnowledgeBaseId", value=knowledge_base.attr_knowledge_base_id)
        CfnOutput(self, "DataSourceId", value=data_source.attr_data_source_id)
        CfnOutput(self, "ChatFunctionName", value=chat.function_name)
        CfnOutput(self, "TableName", value=table.table_name)

    def _budget_guardrails(self, config: DeployConfig, roles: list[iam.IRole]) -> None:
        email = [budgets.CfnBudget.SubscriberProperty(address=config.alert_email, subscription_type="EMAIL")]

        def notification(threshold: int, kind: str = "ACTUAL"):
            return budgets.CfnBudget.NotificationWithSubscribersProperty(
                notification=budgets.CfnBudget.NotificationProperty(
                    comparison_operator="GREATER_THAN",
                    notification_type=kind,
                    threshold=threshold,
                    threshold_type="PERCENTAGE",
                ),
                subscribers=email,
            )

        budget_name = f"{self.stack_name}-monthly"
        budget = budgets.CfnBudget(
            self,
            "MonthlyBudget",
            budget=budgets.CfnBudget.BudgetDataProperty(
                budget_name=budget_name,
                budget_type="COST",
                time_unit="MONTHLY",
                budget_limit=budgets.CfnBudget.SpendProperty(amount=config.monthly_budget_usd, unit="USD"),
            ),
            notifications_with_subscribers=[notification(50), notification(80), notification(100), notification(100, "FORECASTED")],
        )

        deny_bedrock = iam.ManagedPolicy(
            self,
            "BudgetDenyBedrock",
            description="Attached by AWS Budgets when spend passes 120% of budget. Detach to resume.",
            statements=[
                iam.PolicyStatement(effect=iam.Effect.DENY, actions=["bedrock:*", "bedrock-mantle:*"], resources=["*"])
            ],
        )
        budgets_role = iam.Role(self, "BudgetsActionRole", assumed_by=iam.ServicePrincipal("budgets.amazonaws.com"))
        budgets_role.add_to_policy(
            iam.PolicyStatement(
                actions=["iam:AttachRolePolicy", "iam:DetachRolePolicy"],
                resources=[role.role_arn for role in roles],
                conditions={"ArnEquals": {"iam:PolicyARN": deny_bedrock.managed_policy_arn}},
            )
        )
        budgets_role.add_to_policy(
            iam.PolicyStatement(actions=["iam:GetRole", "iam:ListAttachedRolePolicies"], resources=[r.role_arn for r in roles])
        )
        action = budgets.CfnBudgetsAction(
            self,
            "BudgetStopBedrock",
            budget_name=budget_name,
            action_type="APPLY_IAM_POLICY",
            action_threshold=budgets.CfnBudgetsAction.ActionThresholdProperty(type="PERCENTAGE", value=120),
            approval_model="AUTOMATIC",
            notification_type="ACTUAL",
            execution_role_arn=budgets_role.role_arn,
            definition=budgets.CfnBudgetsAction.DefinitionProperty(
                iam_action_definition=budgets.CfnBudgetsAction.IamActionDefinitionProperty(
                    policy_arn=deny_bedrock.managed_policy_arn, roles=[role.role_name for role in roles]
                )
            ),
            subscribers=[budgets.CfnBudgetsAction.SubscriberProperty(address=config.alert_email, type="EMAIL")],
        )
        action.node.add_dependency(budget, budgets_role)
